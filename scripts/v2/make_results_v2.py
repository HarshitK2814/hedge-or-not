"""Generate research/results_v2.md FROM the JSON/CSV outputs in results/v2 (no hand-typed numbers).
Run after all other v2 scripts: python scripts/v2/make_results_v2.py"""
from __future__ import annotations

import json
import re
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
T = ROOT / "results" / "v2" / "tables"
SEEN = "seen period (v1 reported it)"
HASH = "b2e9a0e506a9"


def J(n):
    return json.load(open(T / n))


def ci(s, lo, hi, p=2, pct=False):
    if pct:
        return f"{s*100:.{p}f} [{lo*100:.{p}f}, {hi*100:.{p}f}]"
    return f"{s:.{p}f} [{lo:.{p}f}, {hi:.{p}f}]"


def pp(d, p=2):
    """difference dict -> 'x pp [lo, hi] pp'"""
    return ci(d["diff"], *d["ci95"], p=p, pct=True) + " pp"


def md(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        out.append("| " + " | ".join("" if (isinstance(v, float) and pd.isna(v)) else str(v) for v in r) + " |")
    return "\n".join(out)


def verdict(b: bool) -> str:
    return "SUPPORTED" if b else "NOT SUPPORTED"


def main():
    h, h3, d, d3 = J("h1_h2.json"), J("h3_overfit.json"), J("descriptive.json"), J("d3_var_backtest.json")
    e1, e2, sp = J("e1_conformal.json"), J("e2_pysr.json"), J("seen_period.json")
    spc = pd.read_csv(T / "seen_period.csv")
    rep = pd.read_csv(T / "replication_fund.csv")
    fwd_path = ROOT / "results" / "v2" / "forward" / "forward.csv"
    fwd = pd.read_csv(fwd_path) if fwd_path.exists() else pd.DataFrame(columns=["date", "book", "net_return"])
    n_fwd = fwd["date"].nunique()
    parity_file = ROOT.parent / "qengine" / "PARITY.md"
    parity = parity_file.read_text(encoding="utf-8") if parity_file.exists() else ""
    pm = re.search(r"corr\(run_weights, mbt\) = ([\d.]+); corr\(run_contracts, mbt\) = ([\d.]+)", parity)
    ps = re.search(r"Sharpe: mbt ([\d.\-]+), run_weights ([\d.\-]+), run_contracts ([\d.\-]+)", parity)

    H1, H2, H3p = h["H1"], h["H2"], h3["primary_efa_plus_overlay"]
    H3 = H3p["h3_supported"]
    R = h["rules"]
    gi = h["garch_inspection"]
    o, A = [], None
    A = o.append
    A("# P6 v2 results: Hedge or Not?, institutional benchmarks and a tail-risk lens")
    A("")
    A(f"Generated by `scripts/v2/make_results_v2.py` from `results/v2/tables/*`. Pre-registration v2 hash `{HASH}` (never edited). "
      "Research artifact, not investment advice, not a live-trading instruction.")
    A("")
    A("**Timing.** Ratios are computed at the last business day of month m from data up to and including that day and held from the next business day "
      "(monthly rebalance). Returns are monthly USD returns of EFA plus the currency overlay on a nine-currency basket. "
      "**Costs.** v1 per-currency trade and roll costs, multiplied by 3 on days after the previous VIX close was above 30; no capacity or market-impact model "
      "(an overlay on notional exposure). Sharpe is on total monthly return with no risk-free subtracted unless a table says otherwise. "
      "Confidence intervals are stationary-bootstrap 95% (mean block 6 months, 5000 draws). Choices used data up to 2016-12 only; "
      f"every number dated 2017 or later is labelled `{SEEN}`.")
    A("")
    A("## Bottom line")
    A("")
    A(f"- H1 (rolling 60-month minimum-variance hedge has lower volatility than static 50%): **{verdict(H1['supported'])}**. "
      f"Volatility {H1['vol_mv']*100:.2f}% vs {H1['vol_static50']*100:.2f}%; difference {pp(H1)} over {H1['n_months']} months. "
      f"Window deviation: the prereg said 2006-01..2016-12, but the first full 60-month estimate needs EFA from 2001-09, so the sample starts "
      f"{H1['window'].split('..')[0]} (a sensitivity that fills 2006-01..2006-08 with static 50% gives {pp(h['H1_sensitivity_static50_fallback_full_window'])}, same verdict). "
      f"Caveat: MV is not the lowest-volatility rule. Static 100% has lower volatility "
      f"({R['static100']['ann_vol'][0]*100:.2f}% vs static 50% {R['static50']['ann_vol'][0]*100:.2f}% on 2006-2016), so the claim is only about the 50% benchmark.")
    A(f"- H2 (vol-capped hedge has lower monthly CVaR(95%) than static 50%): **{verdict(H2['supported'])}**. "
      f"CVaR {H2['cvar_volcap']*100:.2f}% vs {H2['cvar_static50']*100:.2f}%; difference {pp(H2)} ({H2['n_months']} months), the interval includes 0. "
      f"The literal GJR-GARCH forecast for CHF explodes (maximum annualised vol {gi['literal_min_max_ann_vol'][1]:.3g}); "
      f"the guarded sensitivity (EWMA fallback on {gi['n_daily_forecasts_rejected_by_guard']} of {gi['n_daily_forecasts']} forecasts) gives {pp(h['H2_guarded_sensitivity'])}, same verdict.")
    A(f"- H3 (v1 is not an overfit pick: PBO < 0.5 and deflated Sharpe > 0.90): **{verdict(H3)}**. "
      f"PBO {H3p['pbo']:.3f} passes; deflated Sharpe {H3p['deflated_sharpe']:.3f} fails the 0.90 bar (n_trials {H3p['n_configs_in_family']}, literal sr_var). "
      f"v1 dynamic3 Sharpe {ci(*H3p['dynamic3_sharpe_ann_ci95'])}, rank {H3p['dynamic3_rank_of_34']} of 34 ({H3p['n_months']} months). "
      f"With an effective-trials count the deflated Sharpe is {h3['sensitivity_effective_trials']['deflated_sharpe_with_n_eff']:.3f}: still below 0.90.")
    A(f"- E1 conformal hedge (exploratory): no value. The interval excludes zero in {(e1['hedge_state_shares_2004_2016']['hedge100'] + e1['hedge_state_shares_2004_2016']['hedge0'])*100:.2f}% of cases, so the book is static 50% in practice.")
    A(f"- E2 PySR hedge formula (exploratory): no value. Spearman {e2['pooled_spearman_pred_vs_next_month_return_2011_2016']['rho']:.3f} "
      f"(p {e2['pooled_spearman_pred_vs_next_month_return_2011_2016']['p']:.2f}); volatility {pp({'diff': e2['portfolio_2011_2016']['diff_eq_minus_static50']['vol'][0], 'ci95': e2['portfolio_2011_2016']['diff_eq_minus_static50']['vol'][1:3]})} worse than static 50%.")
    A("- No dynamic rule beats the simple benchmarks on every lens: the minimum-variance rule trims volatility a little against static 50%, no dynamic rule cuts CVaR against static 50% with an interval that excludes 0, and static 100% had the lowest volatility and CVaR on 2006-2016.")
    A("")
    A("## Hypotheses")
    A("")
    hyp = pd.DataFrame([
        ["H1 minimum-variance hedge", "vol(MV60) < vol(static 50%), CI excludes 0", f"{pp(H1)}; {H1['n_months']} months", verdict(H1["supported"])],
        ["H2 vol-capped hedge", "CVaR95(vol-cap) < CVaR95(static 50%), CI excludes 0", f"{pp(H2)}; {H2['n_months']} months", verdict(H2["supported"])],
        ["H3 overfitting audit", "PBO < 0.5 and deflated Sharpe > 0.90", f"PBO {H3p['pbo']:.3f}; DSR {H3p['deflated_sharpe']:.3f}", verdict(H3)],
    ], columns=["hypothesis", "rule (prereg)", "result", "verdict"])
    A(md(hyp))
    A("")
    A("### H1 and H2 detail (choice window 2006-2016)")
    A("")
    rows = []
    for k in ("unhedged", "static50", "static100", "v1_dynamic3", "mv60", "volcap_wf_literal", "volcap_wf_guarded"):
        r = R[k]
        rows.append([k, r["n_months"], ci(*r["ann_vol"], pct=True), ci(*r["cvar95"], pct=True), ci(*r["sharpe"]),
                     f"{r['mean_hedge_ratio']:.2f}", f"{r['turnover_per_month']:.3f}", f"{r['annual_cost_bp']:.1f}"])
    A(md(pd.DataFrame(rows, columns=["rule", "months", "ann vol % [CI]", "CVaR95 % [CI]", "Sharpe [CI]", "mean hedge ratio", "turnover/month", "cost bp/yr"])))
    A("")
    A(f"MV60 starts at {h['mv_first_ratio_month_end']}. Sensitivities (not in the prereg): 36-month MV window {pp(h['H1_sensitivity_window36'])}; "
      f"MV minus v1 dynamic3 volatility {pp(h['descriptive_differences']['mv_minus_dynamic3_vol'])}.")
    A("")
    A("Walk-forward vol-cap targets (literal GARCH; anchored, 2-year test blocks, min trailing CVaR95, plateau-smoothed):")
    A("")
    A(md(pd.DataFrame([[f["fold_test"], f"{f['chosen_target']:.0%}", f["n_train_months"]] for f in h["walk_forward_literal"]], columns=["test block", "target", "train months"])))
    A("")
    n_lo = sum(f["chosen_target"] == 0.04 for f in h["walk_forward_literal"])
    sf = [f["chosen_target"] for f in sp["volcap_walk_forward"] if f["fold_test"] >= "2017"]
    A(f"The 4% target (the lowest on the grid) is chosen in {n_lo} of {len(h['walk_forward_literal'])} choice-window blocks and in {sum(t == 0.04 for t in sf)} of {len(sf)} seen-period blocks, "
      "so the grid edge is often binding; no wider grid was run. "
      f"The GARCH input is fragile: literal forecasts were rejected by the guard in {gi['rejected_by_currency']['CHF']} CHF and {gi['rejected_by_currency']['AUD']} AUD cases.")
    A("")
    A("### H3 detail")
    A("")
    A(f"- Family: 31 non-empty subsets of the five v1 signals plus static 0/50/100 (34 configs), {h3['window'][0]} to {h3['window'][1]}, v1 costs, EFA plus overlay. "
      f"{h3['note']}.")
    A(f"- Expected maximum annualised Sharpe of 34 null trials {H3p['expected_max_ann_sharpe_null']:.3f}; PSR vs 0 {H3p['psr_vs_0']:.3f}; deflated Sharpe {H3p['deflated_sharpe']:.3f}. "
      f"Best config `{H3p['best_config']}` at {H3p['best_ann_sharpe']:.2f}. All {H3p['n_configs_positive_sharpe']} configs have positive Sharpe because EFA carries the return.")
    sp_ = h3["sensitivity_pure_overlay_excl_degenerate_static0"]
    A(f"- Sensitivity, pure overlay without the all-zero static 0 column: PBO {sp_['pbo']:.3f}, deflated Sharpe {sp_['deflated_sharpe']:.3f}, "
      f"dynamic3 Sharpe {ci(*sp_['dynamic3_sharpe_ann_ci95'])}; verdict unchanged ({verdict(sp_['h3_supported'])}).")
    A("")
    A("## Descriptive")
    A("")
    A("### D1 cost sensitivity (monthly, net)")
    A("")
    D1 = pd.DataFrame(d["D1_cost_sensitivity"])
    D1 = D1[D1.window.str.startswith(("A_", "B_"))]
    D1["Sharpe excess of T-bill [CI]"] = [ci(*s) for s in D1.sharpe_excess]
    D1["cost bp/yr"] = D1.overlay_cost_bp_yr.round(1)
    D1["ann return"] = D1.net_ret_ann.map("{:.3f}".format)
    A(md(D1[D1.rule.isin(["static50", "v1_dynamic3", "mv60", "volcap_wf"])][["window", "regime", "rule", "n_months", "ann return", "Sharpe excess of T-bill [CI]", "cost bp/yr"]]))
    A("")
    piv = D1.pivot_table(index=["window", "rule"], columns="regime", values="sharpe_excess", aggfunc=lambda x: x.iloc[0][0])
    mx = float((piv["2x_stress"] - piv["v1_costs"]).abs().max())
    inc0 = all(s[1] < 0 < s[2] for s in D1.sharpe_excess)
    A(f"Moving from v1 costs to double stress costs changes the Sharpe point estimate by at most {mx:.3f} in these windows, and "
      + ("every Sharpe interval includes 0. " if inc0 else "not every Sharpe interval includes 0. ")
      + "MV60 rows under window A start 2006-10 (first full estimate), so they match window B. "
      "Seen-period D1 rows are in `descriptive.json` (labelled) and not repeated here; use the seen-period table below.")
    A("")
    A("### D2 regret (share of months a rule beats the extremes)")
    A("")
    D2 = pd.DataFrame(d["D2_regret"])
    D2 = D2[D2.rule.isin(["static50", "v1_dynamic3", "mv60", "volcap_wf"]) & D2.window.str.startswith("A_")]
    D2["beats unhedged"] = D2.share_beats_unhedged.map("{:.0%}".format)
    D2["beats fully hedged"] = D2.share_beats_fully_hedged.map("{:.0%}".format)
    A(md(D2[["rule", "window", "n_months", "beats unhedged", "beats fully hedged"]]))
    A("")
    A("### D3 VaR backtest (99% one-month VaR, GJR-GARCH-t one-day sigma x sqrt(21))")
    A("")
    rows = []
    for x in d3["rows"]:
        if x["variant"] != "literal" or not x["window"].startswith("choice") or x["rule"] not in ("static50", "v1_dynamic3", "mv60", "volcap_wf"):
            continue
        rows.append([x["rule"], x["monthly"]["n"], x["monthly"]["breaches"], f"{x['monthly']['kupiec_p']:.3f}",
                     x["daily_secondary"]["n"], f"{x['daily_secondary']['breach_rate']:.2%}", f"{x['daily_secondary']['kupiec_p']:.4f}"])
    A(md(pd.DataFrame(rows, columns=["rule", "monthly n", "monthly breaches", "monthly Kupiec p", "daily n", "daily breach rate", "daily Kupiec p"])))
    A("")
    A(f"{d3['approximation']}. The monthly test has no breaches and little power. The daily breach rates sit above the 1% target and Kupiec rejects for most rules.")
    A("")
    A("### D5 Max-Carry baseline")
    A("")
    rows = [[x["window"], ci(*x["dynamic3_sharpe"]), ci(*x["max_carry_sharpe"]), ci(*x["dynamic3_minus_max_carry"][:3]), x["dynamic3_minus_max_carry"][3],
             "yes" if x["beats_baseline_with_ci_excluding_0"] else "no"] for x in d["D5_max_carry"]]
    A(md(pd.DataFrame(rows, columns=["window", "dynamic3 Sharpe", "Max-Carry Sharpe", "difference [CI]", "months", "beats, CI excludes 0"])))
    A("")
    A("The window labelled with the seen-period tag is the " + SEEN + ".")
    A("")
    A("### D6 CIP-basis sensitivity (window B, 2006-10..2016-12)")
    A("")
    D6 = pd.DataFrame(d["D6_cip_basis"])
    D6["Sharpe excess [CI]"] = [ci(*s) for s in D6.sharpe_excess]
    D6["ann return"] = D6.net_ret_ann.map("{:.4f}".format)
    A(md(D6[D6.rule.isin(["static100", "v1_dynamic3", "mv60", "volcap_wf"])][["basis_bp_per_year", "rule", "ann return", "Sharpe excess [CI]"]]))
    A("")
    A(f"D8 synthetic bond sleeve (equity vs bond, 100% hedge): volatility reduction {d['D8_vol_reduction_100pct_hedge_synthetic_bond_sleeve']:.0%} for the sleeve "
      f"vs {d['D8_vol_reduction_100pct_hedge_equity_EFA']:.0%} for EFA equity, supporting the industry rule to hedge bonds more than equities. {d['D8_construction']}")
    A("")
    A("## Exploratory (never headline)")
    A("")
    ep = e1["portfolio_2004_2016"]
    A(f"**E1 conformal hedge** (ACI alpha 0.2, window 36 months). Coverage {e1['coverage_2004_2016']['overall']:.1%} "
      f"[{e1['coverage_2004_2016']['bootstrap_ci95_month_mean'][0]:.1%}, {e1['coverage_2004_2016']['bootstrap_ci95_month_mean'][1]:.1%}] vs nominal {e1['coverage_2004_2016']['nominal']:.0%}. "
      f"Hedge state shares: 100% {e1['hedge_state_shares_2004_2016']['hedge100']:.2%}, 0% {e1['hedge_state_shares_2004_2016']['hedge0']:.2%}, 50% {e1['hedge_state_shares_2004_2016']['hedge50']:.2%}. "
      f"Volatility {ci(*ep['e1_vol'], pct=True)}% vs static 50% {ci(*ep['static50_vol'], pct=True)}%; the book equals static 50% for practical purposes.")
    A("")
    e2p = e2["portfolio_2011_2016"]
    A(f"**E2 PySR** (trained 2001-09..2010-12, judged once on 2011-2016, {e2p['n_months']} months). Chosen equation `{e2['chosen_equation_sympy']}` "
      f"({e2['n_pareto_equations']} on the Pareto front). Versus static 50%: volatility {pp({'diff': e2p['diff_eq_minus_static50']['vol'][0], 'ci95': e2p['diff_eq_minus_static50']['vol'][1:3]})}, "
      f"CVaR95 {pp({'diff': e2p['diff_eq_minus_static50']['cvar95'][0], 'ci95': e2p['diff_eq_minus_static50']['cvar95'][1:3]})}, "
      f"Sharpe difference {ci(*e2p['diff_eq_minus_static50']['sharpe'][:3])}. Deflated Sharpe {e2['deflated_sharpe_chosen_monthly']:.2f}. {e2['vol_input']}.")
    A("")
    A(f"## Seen period 2017-2026 - {SEEN}")
    A("")
    A(f"v1 already reported 2017-2026, so none of this is out-of-sample evidence. Window {sp['seen_window'][0]} to {sp['seen_window'][1]} (complete months; "
      f"data end {sp['last_data_date']}). Same books, same costs. {sp['sharpe_convention']}. The vol-cap target continued the walk-forward "
      f"(last target {sp['volcap_last_target']:.0%}); the MV rule keeps rolling its 60-month window. "
      "Sharpe is positive for every book, but the unhedged EFA position already has most of it, so it comes from the equity, not the hedge; "
      "the differences between rules are small against their intervals. Read the volatility and CVaR columns for what hedging did.")
    A("")
    for per in ("2006-2016 (choice window)", f"2017-2026 - {SEEN}"):
        s = spc[spc.period == per].copy()
        s["vol % [CI]"] = [ci(a, b, c, pct=True) for a, b, c in zip(s.vol, s.vol_lo, s.vol_hi)]
        s["CVaR95 % [CI]"] = [ci(a, b, c, pct=True) for a, b, c in zip(s.cvar95, s.cvar_lo, s.cvar_hi)]
        s["Sharpe [CI]"] = [ci(a, b, c) for a, b, c in zip(s.sharpe, s.sharpe_lo, s.sharpe_hi)]
        s["hedge ratio"] = s.mean_hedge_ratio.round(2)
        s["cost bp/yr"] = s.annual_cost_bp.round(1)
        A(f"**{per}**")
        A("")
        A(md(s[["book", "window", "n_months", "vol % [CI]", "CVaR95 % [CI]", "Sharpe [CI]", "hedge ratio", "cost bp/yr"]]))
        A("")
    dd = sp["diffs_seen"]
    A(f"Seen-period differences ({SEEN}): MV60 minus static 50% volatility {pp(dd['mv60_minus_static50_vol'])}; "
      f"vol-cap minus static 50% CVaR95 {pp(dd['volcap_wf_minus_static50_cvar95'])}; v1 dynamic3 minus static 50% Sharpe {ci(dd['v1_dynamic3_minus_static50_sharpe']['diff'], *dd['v1_dynamic3_minus_static50_sharpe']['ci95'])}; "
      f"MV60 minus static 100% volatility {pp(dd['mv60_minus_static100_vol'])}. Descriptive only.")
    A("")
    A("Tearsheets (equity, drawdown, rolling Sharpe, monthly table, Monte Carlo, costs, assumptions): `results/v2/tearsheets/*.html`. "
      f"Files with `seen_2017_2026` in the name are the {SEEN}.")
    A("")
    A(f"### Replication check against the live hedged fund ({SEEN})")
    A("")
    A("Monthly overlay net return (v1 costs, as in the v1 table) against the live fund's hedge effect, DDWM minus DWM (the fund's currency-hedged and unhedged twins; DDWM starts 2016-02, so every row falls in the seen period). "
      "The v1 vote rule was built to mimic this fund; the question is whether the minimum-variance and vol-capped rules track it better or worse.")
    A("")
    r = rep.copy()
    r["corr [CI]"] = [ci(a, b, c) for a, b, c in zip(r["corr"], r.corr_lo, r.corr_hi)]
    r["tracking error"] = r.tracking_error_ann.map("{:.1%}".format)
    A(md(r[["book", "window", "n_months", "corr [CI]", "tracking error"]]))
    A("")
    t = rep[rep.window.str.startswith("2017-2024")].set_index("book")["corr"]
    A(f"On 2017-2024 the v1 rule correlates {t['v1_dynamic3']:.2f} with the fund (v1 reported 0.92); the vol-capped rule {t['volcap_wf']:.2f}; the minimum-variance rule {t['mv60']:.2f}. "
      "So the vol-capped rule tracks the fund about as well as static 50%, and the minimum-variance rule tracks it worse than v1. "
      "The fund follows the prospectus-style vote rule, so a rule built differently should not be expected to match it; a lower correlation here is not evidence that the rule is worse.")
    A("")
    A("## Forward test")
    A("")
    if n_fwd == 0:
        A("**0 days and 0 months tracked.** The forward period starts 2026-11 and the data on disk ends before it. First read: 2027-11 (12 monthly points, too few for inference; "
          "tracking only). Run `PREREG_HASH=b2e9a0e506a9 python scripts/v2/forward.py --refresh` after each month-end; it appends only new complete months to "
          "`results/v2/forward/forward.csv`. Books: static 50%, v1 dynamic3, MV60, vol-capped.")
    else:
        A(f"{n_fwd} months tracked. First read: 2027-11 (12 months). Do not read Sharpe before then.")
        A("")
        A(md(fwd.groupby("book")["net_return"].agg(["count", "mean", "std"]).reset_index()))
    A("")
    A("## ManifoldBT cross-check")
    A("")
    A("The qengine backtester was cross-checked against ManifoldBT 0.31.0 before its licence ended (parity diagnostics, not performance claims). "
      "Full tables and mismatches: [`qengine/PARITY.md`](../../qengine/PARITY.md) (shared engine, monorepo root). "
      "**No P6-specific ManifoldBT run was made**: P6 is a monthly currency overlay on notional exposure, which ManifoldBT's price-and-position model does not represent, "
      "and the P6 numbers above come from the project's own monthly code; qengine supplies only the tearsheet, Monte Carlo and look-ahead checker.")
    if pm and ps:
        A("")
        A(f"Engine parity (P7 trend weights): daily-return correlation with ManifoldBT {pm.group(1)} (run_weights), {pm.group(2)} (run_contracts); "
          f"Sharpe mbt {ps.group(1)}, run_weights {ps.group(2)}, run_contracts {ps.group(3)}.")
    A("")
    A("## Limitations")
    A("")
    A("- Interbank rate differentials stand in for 1-month forward points; the D6 basis sensitivity is a bound, not a measurement.")
    A("- PPP is today's vintage; EFA stands in for the fund's dividend-weighted index.")
    A("- The H1 window starts 2006-09, not 2006-01 (first full 60-month estimate); the full-window sensitivity gives the same verdict.")
    A("- The literal GJR-GARCH forecast for CHF explodes; H2 is reported literally and with a labelled guard. The lowest vol-cap target on the grid (4%) is chosen in most blocks, so the grid edge often binds.")
    A("- No capacity or market-impact model: the overlay is sized on notional exposure, and costs are v1 bp plus the VIX stress multiplier.")
    A("- 2017-2026 is a seen period. One USD-carry regime dominates it. Only the forward test can add unseen evidence, and it has 0 months so far.")
    A("- Monthly VaR backtests have about 150 observations and little power.")
    A("")
    (ROOT / "research" / "results_v2.md").write_text("\n".join(o) + "\n", encoding="utf-8")
    print("wrote research/results_v2.md", len(o), "lines")


if __name__ == "__main__":
    main()
